SELECT S.NAME,R.ROOM_NO,H.HOSTEL_NAME
FROM STUDENTS S
JOIN ROOMS R ON S.ROOM_ID ==R.ROOM_ID 
JOIN HOSTELS H ON R.HOSTEL_ID==H.HOSTEL_ID 


SELECT S.NAME,C.COMPLAINT_TEXT,MF.STAFF_NAME
FROM STUDENTS S
JOIN COMPLAINTS C ON C.STUDENT_ID ==S.STUDENT_ID 
JOIN MAINTENANCE_STAFF MF ON C.STAFF_ID ==MF.STAFF_ID 

SELECT C.COMPLAINT_ID,C.COMPLAINT_TEXT,C.CREATED_AT,CS.UPDATED_AT,CS.STATUS
FROM COMPLAINTS C
JOIN COMPLAINT_STATUS CS ON C.COMPLAINT_ID==CS.COMPLAINT_ID 







