CREATE TABLE HOSTELS(
	HOSTEL_ID INTEGER PRIMARY KEY,
	HOSTEL_NAME VARCHAR(10) NOT NULL
);





CREATE TABLE ROOMS(
	ROOM_ID INTEGER PRIMARY KEY,
	ROOM_NO INT NOT NULL,
	HOSTEL_ID INT NOT NULL,
	CAPACITY INT NOT NULL,
	UNIQUE(ROOM_NO,HOSTEL_ID),
	FOREIGN KEY (HOSTEL_ID) REFERENCES HOSTELS(HOSTEL_ID)
);


CREATE TABLE STUDENTS(
	STUDENT_ID INTEGER PRIMARY KEY,
	NAME VARCHAR(30) NOT NULL,
	ROOM_ID INT NOT NULL,
	FOREIGN KEY (ROOM_ID) REFERENCES ROOMS(ROOM_ID)
);


CREATE TABLE STUDENT_PHONE(
	PHONE_ID INTEGER PRIMARY KEY,
	STUDENT_ID  INT NOT NULL,
	PHONE_NO VARCHAR(10),
	FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
);


CREATE TABLE MAINTENANCE_STAFF(
	STAFF_ID INTEGER PRIMARY KEY,
	STAFF_NAME VARCHAR(30) NOT NULL
);


CREATE TABLE WARDENS(
	WARDEN_ID INTEGER PRIMARY KEY,
	WARDEN_NAME VARCHAR(30) NOT NULL,
	HOSTEL_ID INT NOT NULL,
	FOREIGN KEY (HOSTEL_ID) REFERENCES HOSTELS(HOSTEL_ID)
);



CREATE TABLE COMPLAINTS(
	COMPLAINT_ID INTEGER PRIMARY KEY,
	COMPLAINT_TEXT TEXT NOT NULL,
	STAFF_ID INT NOT NULL,
	STUDENT_ID INT NOT NULL,
	CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (STAFF_ID) REFERENCES MAINTENANCE_STAFF(STAFF_ID),
	FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
);


CREATE TABLE COMPLAINT_STATUS(
	STATUS_ID INTEGER PRIMARY KEY,
	COMPLAINT_ID INT NOT NULL ,
	STATUS VARCHAR(20) NOT NULL,
	UPDATED_AT TIMESTAMP,
	FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(COMPLAINT_ID)
);



